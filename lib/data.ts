/** Image embarquée (`require`) ou image publiée à une adresse. */
export type Photo = number | { uri: string };

export type Product = {
  id: string;
  name: string;
  variety: string;
  category: CategoryId;
  origin: string;
  price: number;
  /** 'kg' : vendu au poids par paliers de `step` kg. 'unit' : vendu à l'unité. */
  unit: 'kg' | 'unit';
  unitLabel: string;
  noun: [string, string];
  step: number;
  /** Quantité minimale et maximale par commande (par défaut : un palier, vingt paliers). */
  min?: number;
  max?: number;
  /** Espace professionnel : prix de gros, selon l'incoterm affiché dans `priceTag`. */
  pro?: boolean;
  priceTag?: string;
  /** Ligne d'offre professionnelle : produit d'origine et mode de transport. */
  productId?: string;
  mode?: 'avion' | 'bateau' | null;
  /** Vrai : seules les quantités multiples du palier sont acceptées (avion, conteneurs). */
  strictStep?: boolean;
  /** Vrai : le prix de cette offre n'est pas défini. Aucun total n'est alors calculé. */
  noPrice?: boolean;
  /** Ce qui manque quand `noPrice` est vrai : le prix lui-même, ou le poids du conteneur. */
  missing?: 'prix' | 'poids' | null;
  /** Prix tel qu'il est configuré et son unité, s'ils diffèrent de l'unité commandée. */
  shownPrice?: number | null;
  shownUnit?: string;
  /** Bateau : kilos par conteneur (`null` : non défini). */
  containerKg?: number | null;
  containerLabel?: string;
  /** Produit du catalogue professionnel : ses offres commandables (avion, bateau…). */
  offers?: Product[];
  tint: string;
  season: number[];
  bio: boolean;
  rating: number;
  reviews: number;
  kcal: number;
  fibres: number;
  vitC: number;
  description: string;
  tip: string;
  image: Photo;
};

